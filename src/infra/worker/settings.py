from typing import Any

from arq import cron
from arq.connections import RedisSettings, create_pool

from config import settings
from infra.worker.cron_tasks.stock_replenishment import the_morning_has_come_task
from infra.worker.cron_tasks.stock_report import stock_report_task
from infra.worker.tasks.domain_event_processor import domain_event_processor

"""
Краткий глоссарий:
    - arq-worker, worker — процесс-рабочий. Ему всё равно что исполнять, его роль - просто крутится в фоне,
    посматривать смотреть в очередь, при появлении задания - подхватывать его и исполнить соответствующий таск.
    
    - arq-task, task, job — функция или callable-класс, декларирующий "такая-то задача решается так-то".
        
    - задача, задание - просьба вызывать определённый таск с определенными параметрами. Они помещаются клиентами в 
    очередь, откуда их подхватывают воркеры и исполняют. Условно выглядит: `{task_name: ..., args: ..., kwargs: ...}`.
    
    - очередь заданий, просто "очередь" - условная коробка, в которую можно скидывать задачи, из которой их будут 
    подхватывать воркеры и исполнять. В данном проекте роль коробки выполняет Redis.

Аналогии из реального мира:
    - worker - повар на кухне ресторана, если нет заказов - он просто стоит и ожидает их появления.
    - task - рецепт блюда, который повар может приготовить ("как готовить пасту карбонара").
    - задание - заказ, который официант передаёт на кухню ("приготовь пасту карбонара, с беконом, большую порцию").
    
Архитектурные решения:
    Arq весьма гибок и позволяет как угодно организовать воркеры.

    Можно сделать так, чтобы хоть вообще все таски / задачи выполнялись в одном единственном воркере:
        - один повар-универсал на весь ресторан, который может готовить что угодно, хоть кофе, хоть пиццу, хоть суши.

    И тем не менее, в целях предотвращения хаоса и следования принципу "единственной ответственности" - 
    рекомендуется по мере необходимости выделять отдельные воркеры для разных категорий задач. Например:
        - суши-шеф - готовит только суши
        - пицца-мастер - занимается только пиццами
        - бариста - готовит только кофе, чай, коктейли и т.п.

    В нашем случае уже выделены два воркера:
        DomainEventsProcessorSettings - только для обработки доменных событий:
            - проверяет по регистру событий, есть ли заинтересованные в нём хэндлеры
            - если есть, то передаёт каждому из них восстановленный объект события и вызывает их исполнение
        Он может стать первым кандидатом на горизонтальное масштабирование, которое можно реализовать
        просто через запуск дополнительных таких же воркеров (процессов ОС), если потребуется.

        CronJobsSettings - только для запуска периодических задач по расписанию (cron-задач):
            - таски для него не содержат никакой бизнес логики
            - их единственная роль: собрать объект доменного события и закинуть его в шину и завершится
            - шина просто добавит в arq-очередь соответствующее задание, которое подхватят соответствующие воркеры
        Этот воркер скорее всего очень долго не потребует масштабирования, потому что его единственная роль - просто 
        в нужное время породить событие, закинуть его в шину и всё. Всю остальную работу уже подхватят хэндлеры, т.е.
        воркеры, отвечающие за обработку доменных событий и вызовы нужных хэндлеров.
        
        Собственно, это и есть пример разделения ответственности: таски для воркеров - сугубо инженерные штуки, 
        конкретные реализации для текущей инфраструктуры - остаются простыми, максимально абстрагированными от 
        бизнес-логики, а потому они легко масштабируемы и элементарны в рефакторинге; в то время как бизнес-сценарии -
        по прежнему будут упакованы и разложены по хэндлерам и событиям - буквально, как им и предписывают принципы DDD.

        Каждый из воркеров исполняется в своём рантайме, но они все работают с одной и той же очередью в Redis.
"""


class _GeneralWorkerSettings:
    """
    Общие настройки конфигурации для arq-воркеров.

    Таски, перечисляемые в атрибуте `functions` будут доступны для ручной постановки в очередь через arq-клиент.
    Таски в `cron_jobs` воркер запускает сам, по расписанию — вручную их ставить в очередь не нужно.
    Таски должны быть объявлены внутри соответствующих *Settings-классов, здесь расположены лишь общие настройки.
    """

    redis_settings = RedisSettings.from_dsn(str(settings.redis_url))

    # Максимальное количество тасков, выполняемых параллельно одним воркером.
    max_jobs = 10

    # Таймаут выполнения одного таска в секундах. По истечении arq отменяет таск.
    job_timeout = 300

    # Сколько секунд хранить результат завершённого таска в Redis.
    # Актуально, если где-то вычитывается результат через arq-клиент (job.result()).
    keep_result = 3600

    # Повторять ли таск автоматически при падении с исключением.
    retry_jobs = True

    # Максимальное количество попыток запуска таска (включая первую).
    max_tries = 3

    @staticmethod
    async def on_startup(ctx: dict) -> None:
        """Создаёт Redis-соединение один раз при старте воркера и кладёт его в ctx для всех тасков."""
        redis_connection = RedisSettings.from_dsn(str(settings.redis_url))
        ctx['redis'] = await create_pool(redis_connection)

    @staticmethod
    async def on_shutdown(ctx: dict) -> None:
        """Закрывает Redis-соединение при остановке воркера."""
        await ctx['redis'].aclose()

    def __init_subclass__(cls, **kwargs: Any) -> None:
        """
        arq читает настройки воркера через cls.__dict__, игнорируя унаследованные атрибуты.
        Этот хук автоматически копирует все общие настройки из базового класса в __dict__ каждого подкласса,
        если подкласс не переопределил их явно.
        """
        super().__init_subclass__(**kwargs)
        for attr, value in vars(_GeneralWorkerSettings).items():
            if not attr.startswith('_') and attr not in vars(cls):
                setattr(cls, attr, value)


class DomainEventsProcessorSettings(_GeneralWorkerSettings):
    """
    Конфигурация для воркера, который обслуживает только доменные события и дёргает их обработчики.

    Запуск: python -m arq infra.worker.settings.DomainEventsProcessorSettings
      либо: python src/domain_events_worker.py
    """

    functions = [  # type: ignore[assignment]
        domain_event_processor,
    ]


class CronJobsSettings(_GeneralWorkerSettings):
    """
    Конфигурация arq-воркера для периодических тасков (запуск по расписанию).

    Запуск: python -m arq infra.worker.settings.CronJobsSettings
      либо: python src/cron_tasks_worker.py
    """

    functions = [  # type: ignore[assignment]
        stock_report_task,
    ]

    cron_jobs = [
        cron(stock_report_task, hour=6, minute=0),  # каждый день в 06:00
        cron(the_morning_has_come_task, hour=6, minute=5),  # каждый день в 06:05, сразу после отчёта
    ]
