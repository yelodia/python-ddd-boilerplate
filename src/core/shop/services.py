from core.shop.entities import Product, Cart


class Shopping:
    """
    Сервис, который отвечает за бизнес-логику, связанную с покупками.
     - положить товар в корзину
     - убрать товар из корзины
     - очистить корзину
     - оформить заказ (трансформировать корзину в заказ)
     - и т.д.

    Доменный сервис - это всегда stateless-класс.

    Все эти операции могут быть реализованы в виде методов данного сервиса.

    Эти методы могут быть единственным способом изменить состояние корзины и её содержимого (если есть такая
    договорённость внутри команды разработки). Например, чтобы избежать дублирования кода.

    В таком случае все юзкейсы, которые как-то влияют на состояние корзины, должны будут использовать
    именно эти методы, а не обращаться напрямую к доменным штукам.

    Это рекомендательный случай, когда бизнес-логику _можно_ выносить в сервис.

    Обязательный случай, когда бизнес-логику _нужно_ выносить в сервис - это когда она либо слишком объемная,
    либо затрагивает сразу несколько сущностей из _разных_ доменов. Таковой она может становиться не сразу,
    а лишь по мере роста проекта - это нормально.

    ############################################################################
    Напоминалка: как отличить доменный сервис от других разновидностей сервисов?
    ############################################################################
    Правило пустого конструктора: если в конструктор хочется передать репозиторий, HTTP-клиент, логгер
    или очередь — это не доменный сервис. Доменный сервис не должен знать ничего о том, как и где его
    будут использовать. Он просто выполняет свою работу, не заботясь о том, кто его вызывает и зачем.

    Правило глагола: доменный сервис — это глагол, который не принадлежит ни одному существительному.
    Если операция естественно читается как объект.действие() — она принадлежит объекту, а не сервису.

    # Тест: кому принадлежит это действие?
    # "Счёт снимает деньги" → account.withdraw() — метод агрегата
    # "Система переводит деньги между счетами" → MoneyTransferService — доменный сервис
    # "Приложение отправляет письмо после перевода" → UseCase + EmailAdapter

    Правило состояния: если у сервиса появляется изменяемое поле — это либо агрегат, либо ошибка проектирования.
    Доменный сервис всегда stateless. В терминах python это можно выразить как "методы доменного сервиса
    обязаны быть статическими, а конструктор — отсутствовать".

    # ❌ Состояние в доменном сервисе — это агрегат, притворяющийся сервисом
    class PricingService:
        def __init__(self):
            self._last_calculated_price = None  # ← это не сервис

    Правило чистоты: если вызов доменного сервиса с одними и теми же аргументами даёт
    разные результаты — в него протекает инфраструктура (время, случайность, БД).
    Исключение — если недетерминизм сам по себе часть домена.
    """

    @staticmethod
    def put_product_to_cart(product: Product, cart: Cart, pcs: int) -> None:
        if not product.id:
            raise ValueError('Нельзя положить в корзину товар, который ещё не записан в БД')

        if not issubclass(type(product), Product):
            raise TypeError(f'В корзину можно положить только товар, а не {type(product)}')

        product.take_from_shelf(pcs)
        cart.alternate_put_product(product.id, product.price, pcs)
